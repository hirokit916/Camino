def stats(items):
    return '<div class="cr-stats rise">' + ''.join('<div><b>%s</b><p>%s</p><span>%s</span></div>' % x for x in items) + '</div>'

def phasemap(items):
    out = []
    for n, (pid, title, chips) in enumerate(items, 1):
        out.append('<li><a class="sm-h" href="#%s"><i>%d</i>%s</a><ul>%s</ul></li>' % (pid, n, title, ''.join('<li>%s</li>' % c for c in chips)))
    return '<ol class="ss-map rise">%s</ol>' % ''.join(out)

def matrix(cols, rows):
    h = '<thead><tr><th>企業</th>' + ''.join('<th>%s</th>' % c for c in cols) + '</tr></thead>'
    b = ''.join('<tr><th>%s<small>%s</small></th>%s</tr>' % (name, kind, ''.join('<td>%s</td>' % ('<i class="dot" aria-label="あり">●</i>' if v else '<span class="no" aria-label="公式ページで確認できず">—</span>') for v in vals)) for name, kind, vals in rows)
    return '<p class="ehint">表は横にスクロールできます →</p><div class="cr-mxw rise"><table class="cr-mx">%s<tbody>%s</tbody></table></div>' % (h, b)

def timeline(rows):
    return '<ol class="tl rise">' + ''.join('<li><div class="tl-when"><b>%s</b><span>%s</span></div><div class="tl-what">%s</div></li>' % (w, s, ''.join('<p>%s</p>' % x for x in what)) for w, s, what in rows) + '</ol>'

