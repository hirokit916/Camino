"""Career (就職活動) column: three articles + hub. Facts are from official pages listed in each article's sources."""

def flow(steps):
    return '<ol class="cr-flow">' + ''.join('<li><b>%s</b>%s</li>' % (a, ('<span>%s</span>' % b) if b else '') for a, b in steps) + '</ol>'

def memo(html, label=''):
    return '<div class="cr-memo rise">%s%s</div>' % (('<p class="cr-ml">%s</p>' % label) if label else '', html)

def table(head, rows):
    h = '<thead><tr>' + ''.join('<th>%s</th>' % x for x in head) + '</tr></thead>'
    b = ''.join('<tr><th>%s</th>%s</tr>' % (r[0], ''.join('<td data-l="%s">%s</td>' % (head[i + 1], c) for i, c in enumerate(r[1:]))) for r in rows)
    return '<div class="ewrap rise"><table class="etbl stk">%s<tbody>%s</tbody></table></div>' % (h, b)

def step(n, id_, h3, sub=''):
    return '<div class="step" id="%s"><span class="step-n">%d</span><div><h3>%s</h3>%s</div></div>' % (id_, n, h3, ('<p class="step-sub">%s</p>' % sub) if sub else '')

def company(name, tag, rows, steps, note, src):
    dl = ''.join('<div><dt>%s</dt><dd>%s</dd></div>' % r for r in rows)
    return ('<article class="cr-co rise"><header><h4>%s</h4><span class="cr-tag">%s</span></header><dl>%s</dl>%s%s<p class="cr-src">出典：%s</p></article>'
            % (name, tag, dl, flow(steps), ('<p class="cr-note">%s</p>' % note) if note else '', src))

def ext(url, label):
    return '<a href="%s" target="_blank" rel="noopener">%s</a>' % (url, label)

